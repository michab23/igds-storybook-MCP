/**
 * Build data/icon-index.json from an installed @igds/icons package.
 *
 * Run: npm run build:icons -- /path/to/node_modules/@igds/icons
 *
 * Stores only hashes of each icon's markup, keyed to its export name (see src/icon-index.ts).
 */
import { readFileSync, readdirSync, writeFileSync } from 'fs';
import { join } from 'path';
import { hashIconMarkup, IconIndex } from '../src/icon-index.js';

const dir = process.argv[2];
if (!dir) {
  console.error('Usage: npm run build:icons -- /path/to/node_modules/@igds/icons');
  process.exit(1);
}

const version = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf-8')).version as string;
const icons: Record<string, string> = {};
let collisions = 0;

for (const file of readdirSync(join(dir, 'lib')).filter((f) => f.endsWith('.js') && f !== 'index.js')) {
  const match = readFileSync(join(dir, 'lib', file), 'utf-8').match(/export const (\w+) = '((?:[^'\\]|\\.)*)';/);
  if (!match) continue;
  const [, name, markup] = match;
  const hash = hashIconMarkup(markup.replace(/\\'/g, "'"));
  if (icons[hash] && icons[hash] !== name) collisions++;
  icons[hash] ??= name;
}

const index: IconIndex = {
  _comment: 'Hash of normalised SVG markup -> @igds/icons export name. Hashes only, no artwork. Generated by scripts/build-icon-index.ts.',
  version,
  icons,
};
writeFileSync(join(process.cwd(), 'data', 'icon-index.json'), JSON.stringify(index, null, 0) + '\n');
console.log(`icon-index: ${Object.keys(icons).length} icons from @igds/icons ${version}${collisions ? `, ${collisions} identical-markup aliases` : ''}`);
